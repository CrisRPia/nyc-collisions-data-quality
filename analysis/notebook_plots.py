"""Validated plotting interface for the notebook's small matplotlib subset.

Matplotlib's dynamic keyword setters have incomplete static signatures. This
protocol describes the public methods we use and validates their presence,
while the notebook validates numeric plotting data with separate TypeAdapters.
"""

from collections.abc import Sequence
from typing import Protocol, runtime_checkable

from pydantic import ConfigDict, TypeAdapter


@runtime_checkable
class PlotAxes(Protocol):
    def barh(self, y: Sequence[str] | Sequence[float], width: Sequence[float], *, height: float = ..., **kwargs: object) -> object: ...
    def bar(self, x: Sequence[str], height: Sequence[int], **kwargs: object) -> object: ...
    def set(self, **kwargs: object) -> object: ...
    def grid(self, **kwargs: object) -> None: ...
    def legend(self, **kwargs: object) -> object: ...
    def tick_params(self, **kwargs: object) -> None: ...
    def plot(self, x: Sequence[float], y: Sequence[float], **kwargs: object) -> object: ...
    def scatter(self, x: Sequence[float], y: Sequence[float], **kwargs: object) -> object: ...
    def set_aspect(self, aspect: float) -> None: ...


PLOT_AXES_ADAPTER = TypeAdapter(PlotAxes, config=ConfigDict(arbitrary_types_allowed=True))
